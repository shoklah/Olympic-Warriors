"""
UserProfile and players' photos (olympic_warriors/avatars.py): store_photo() validates an
upload, re-encodes it as two WebP squares under fresh names and deletes the files it
replaces once the transaction commits; remove_photo() takes both down the same way, and a
deleted profile (its user's cascade included) takes its files with it. Both read the row
under lock, so a stale copy of the profile can neither dodge a lock nor orphan files. Images
are generated by Pillow in memory, and MEDIA_ROOT is a temporary folder per test.
"""

