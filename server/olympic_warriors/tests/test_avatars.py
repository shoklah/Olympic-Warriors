class TestErasure(MediaRootTestCase):
    """A profile's files go with it, whether it is deleted itself or with its user, once
    the deletion commits."""

    def setUp(self):
        super().setUp()
        self.ana = User.objects.create(username="ana", first_name="Ana", last_name="Lopez")
        self.profile = UserProfile.objects.create(user=self.ana)
        store_photo(self.profile, upload(encode(picture(), "JPEG")))
        self.assertEqual(len(self.avatar_files()), 2)

    def test_deleting_the_user_deletes_the_files(self):
        with self.captureOnCommitCallbacks(execute=True):
            self.ana.delete()
            self.assertEqual(len(self.avatar_files()), 2)  # not before the commit

        self.assertEqual(self.avatar_files(), [])

    def test_deleting_the_profile_deletes_the_files(self):
        with self.captureOnCommitCallbacks(execute=True):
            UserProfile.objects.filter(pk=self.profile.pk).delete()

        self.assertEqual(self.avatar_files(), [])

    def test_a_rolled_back_deletion_keeps_them(self):
        with self.captureOnCommitCallbacks(execute=True) as callbacks:
            with self.assertRaises(RuntimeError), transaction.atomic():
                self.ana.delete()
                raise RuntimeError("changed my mind")

        self.assertEqual(callbacks, [])
        self.assertEqual(len(self.avatar_files()), 2)
        self.assertTrue(UserProfile.objects.filter(pk=self.profile.pk).exists())

    def test_a_profile_without_a_photo_leaves_nothing_to_do(self):
        bob = User.objects.create(username="bob")
        UserProfile.objects.create(user=bob)

        with self.captureOnCommitCallbacks(execute=True) as callbacks:
            bob.delete()

        self.assertEqual(callbacks, [])
        self.assertEqual(len(self.avatar_files()), 2)  # Ana's
